// Build minifies first-party JavaScript into tracked generated artifacts. In
// check mode it performs no writes and returns an error for missing or stale
// output.
func Build(root string, check bool) ([]ArtifactResult, error) {
	results := make([]ArtifactResult, 0, len(defaultArtifacts))
	var drift []string
	for _, spec := range defaultArtifacts {
		generated, err := buildArtifact(root, spec)
		if err != nil {
			return nil, err
		}
		outputPath := filepath.Join(root, filepath.FromSlash(spec.output))
		if check {
			current, readErr := os.ReadFile(outputPath)
			if readErr != nil || !bytes.Equal(current, generated) {
				drift = append(drift, spec.output)
			}
		} else if err := os.WriteFile(outputPath, generated, 0o644); err != nil {
			return nil, fmt.Errorf("write %s: %w", spec.output, err)
		}
		results = append(results, ArtifactResult{
			Output: spec.output,
			Inputs: append([]string(nil), spec.inputs...),
		})
	}
	if len(drift) > 0 {
		sort.Strings(drift)
		return results, fmt.Errorf("generated JavaScript drift: %s; run go run ./cmd/jsbuild", strings.Join(drift, ", "))
	}
	return results, nil
}

func buildArtifact(root string, spec artifact) ([]byte, error) {
	var combined bytes.Buffer
	for index, input := range spec.inputs {
		content, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(input)))
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", input, err)
		}
		if index > 0 {
			combined.WriteString(";\n")
		}
		combined.Write(content)
		combined.WriteByte('\n')
	}

	result := api.Transform(combined.String(), api.TransformOptions{
		Charset:           api.CharsetUTF8,
		Format:            api.FormatIIFE,
		LegalComments:     api.LegalCommentsNone,
		Loader:            api.LoaderJS,
		LogLevel:          api.LogLevelSilent,
		MinifyIdentifiers: true,
		MinifySyntax:      true,
		MinifyWhitespace:  true,
		Sourcefile:        strings.Join(spec.inputs, "+"),
		Supported:         map[string]bool{"arrow": true},
		Target:            api.ES2020,
		TreeShaking:       api.TreeShakingTrue,
	})
	if len(result.Errors) > 0 {
		messages := api.FormatMessages(result.Errors, api.FormatMessagesOptions{Kind: api.ErrorMessage})
		return nil, errors.New(strings.Join(messages, "\n"))
	}
	output := make([]byte, 0, len(generatedHeader)+len(result.Code))
	output = append(output, generatedHeader...)
	output = append(output, result.Code...)
	if len(output) == 0 || output[len(output)-1] != '\n' {
		output = append(output, '\n')
	}
	return output, nil
}

// SourceFiles returns authored first-party JavaScript in stable path order.
func SourceFiles(root string) (map[string][]byte, error) {
	paths := make([]string, 0)
	for _, relativeBase := range []string{"assets/js/src", "site/assets/js/src"} {
		base := filepath.Join(root, filepath.FromSlash(relativeBase))
		err := filepath.WalkDir(base, func(path string, entry os.DirEntry, walkErr error) error {
			if walkErr != nil {
				return walkErr
			}
			if entry.IsDir() || filepath.Ext(path) != ".js" {
				return nil
			}
			paths = append(paths, path)
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	sort.Strings(paths)
	sources := make(map[string][]byte, len(paths))
	for _, path := range paths {
		content, err := os.ReadFile(path)
		if err != nil {
			return nil, err
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return nil, err
		}
		sources[filepath.ToSlash(relative)] = content
	}
	return sources, nil
}

// ValidateJavaScript parses every authored source with the pinned esbuild
// parser. It does not rewrite source formatting.
func ValidateJavaScript(sources map[string][]byte) error {
	paths := make([]string, 0, len(sources))
	for path := range sources {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	var failures []string
	for _, path := range paths {
		result := api.Transform(string(sources[path]), api.TransformOptions{
			Loader:     api.LoaderJS,
			LogLevel:   api.LogLevelSilent,
			Sourcefile: path,
			Target:     api.ES2020,
		})
		if len(result.Errors) == 0 {
			continue
		}
		failures = append(failures, api.FormatMessages(result.Errors, api.FormatMessagesOptions{Kind: api.ErrorMessage})...)
	}
	if len(failures) > 0 {
		return errors.New(strings.Join(failures, "\n"))
	}
	return nil
}
