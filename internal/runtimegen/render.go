package runtimegen

import (
	"bytes"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

func renderVendorConstants(model Model) string {
	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by runtimegen. DO NOT EDIT.\n")
	buffer.WriteString("// Source of truth: muamba.yaml and assets/runtime.overlay.yaml\n\n")
	buffer.WriteString("package assets\n\nconst (\n")
	for _, asset := range allAssets(model) {
		fmt.Fprintf(&buffer, "\t%sURL = %q\n", asset.GoName, asset.LocalURL)
		if asset.Version != "" {
			fmt.Fprintf(&buffer, "\truntimeVersion%s = %q\n", asset.GoName, asset.Version)
		}
		if asset.URL != "" {
			fmt.Fprintf(&buffer, "\t%sCDNURL = %q\n", asset.GoName, asset.URL)
			fmt.Fprintf(&buffer, "\t%sIntegrity = %q\n", asset.GoName, asset.Integrity)
		}
	}
	buffer.WriteString(")\n\n")
	buffer.WriteString("// RuntimeHash returns the normalized Muamba content hash for a vendored runtime role.\n")
	buffer.WriteString("func RuntimeHash(role RuntimeAssetRole) (string, bool) {\n\tswitch role {\n")
	for _, asset := range model.Dependencies {
		if asset.Resource == "" {
			continue
		}
		fmt.Fprintf(&buffer, "\tcase RuntimeRole%s:\n\t\treturn MuambaHash(%q, %q)\n", asset.RoleGoName, asset.Resource, asset.Download)
	}
	buffer.WriteString("\tdefault:\n\t\treturn \"\", false\n\t}\n}\n")
	return formatGo(buffer.String())
}

func renderRuntimeManifest(model Model) string {
	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by runtimegen. DO NOT EDIT.\n")
	buffer.WriteString("// Source of truth: muamba.yaml and assets/runtime.overlay.yaml\n\n")
	buffer.WriteString("package assets\n\n")
	buffer.WriteString("const (\n")
	for _, asset := range allAssets(model) {
		fmt.Fprintf(&buffer, "\t// RuntimeRole%s identifies %s.\n", asset.RoleGoName, asset.Name)
		fmt.Fprintf(&buffer, "\tRuntimeRole%s RuntimeAssetRole = %q\n", asset.RoleGoName, asset.Role)
	}
	buffer.WriteString(")\n\n")
	buffer.WriteString("func defaultRuntimeLoader() RuntimeAsset {\n\treturn ")
	writeRuntimeAsset(&buffer, model.Loader)
	buffer.WriteString("\n}\n\n")
	buffer.WriteString("func defaultRuntimeDependencies() []RuntimeAsset {\n\treturn []RuntimeAsset{\n")
	for _, asset := range model.Dependencies {
		buffer.WriteString("\t\t")
		writeRuntimeAsset(&buffer, asset)
		buffer.WriteString(",\n")
	}
	buffer.WriteString("\t}\n}\n\n")
	buffer.WriteString("func defaultRuntimeMetadata() []RuntimeAssetMetadata {\n\treturn []RuntimeAssetMetadata{\n")
	for _, asset := range allAssets(model) {
		fmt.Fprintf(&buffer, "\t\t{Role: RuntimeRole%s, Name: %q, Version: %q, PackageName: %q, ProvenanceURL: %q, Homepage: %q, License: %q, LicenseURL: %q, Purpose: %q},\n", asset.RoleGoName, asset.Name, asset.Version, asset.PackageName, asset.ProvenanceURL, asset.Homepage, asset.License, asset.LicenseLocalURL, asset.Purpose)
	}
	buffer.WriteString("\t}\n}\n")
	return formatGo(buffer.String())
}

func writeRuntimeAsset(buffer *bytes.Buffer, asset Asset) {
	primary := asset.GoName + "URL"
	if asset.URL != "" {
		primary = asset.GoName + "CDNURL"
	}
	fmt.Fprintf(buffer, "RuntimeAsset{Role: RuntimeRole%s, Kind: RuntimeAssetScript, PrimaryURL: %s, LocalURL: %sURL", asset.RoleGoName, primary, asset.GoName)
	if asset.URL != "" && asset.Integrity != "" {
		fmt.Fprintf(buffer, ", Integrity: %sIntegrity", asset.GoName)
	}
	if asset.Enabled {
		buffer.WriteString(", Enabled: true")
	}
	if asset.IncludeInMinimal {
		buffer.WriteString(", IncludeInMinimal: true")
	}
	if asset.Defer {
		buffer.WriteString(", Defer: true")
	}
	if asset.WaitForWindowLoaded {
		buffer.WriteString(", WaitForWindowLoaded: true")
	}
	buffer.WriteString("}")
}

func renderRuntimeAttributions(model Model) string {
	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by runtimegen. DO NOT EDIT.\n")
	buffer.WriteString("// Source of truth: muamba.yaml and assets/runtime.overlay.yaml\n\n")
	buffer.WriteString("package legalpages\n\n")
	buffer.WriteString("import \"github.com/araihu/goshtoso/assets\"\n\n")
	buffer.WriteString("var runtimeAttributionDefinitions = []runtimeAttributionDefinition{\n")
	for _, asset := range model.Dependencies {
		if !asset.Attribution {
			continue
		}
		fmt.Fprintf(&buffer, "\t{Attribution: attribution{Name: %q, Href: %q, License: %q, Note: %q}, Role: assets.RuntimeAssetRole(%q), Version: %s, FallbackLocalURL: assets.%sURL},\n", asset.Name, asset.Homepage, asset.License, asset.Purpose, asset.Role, versionFunction(asset), asset.GoName)
	}
	buffer.WriteString("}\n")
	return formatGo(buffer.String())
}

func versionFunction(asset Asset) string {
	switch asset.Resource {
	case "alpinejs":
		return "assets.AlpineVersion"
	case "htmx":
		return "assets.HTMXVersion"
	case "htmx-ext-sse":
		return "assets.HTMXExtSSEVersion"
	case "htmx-ext-ws":
		return "assets.HTMXExtWSVersion"
	default:
		panic("runtimegen: missing version function for " + asset.Resource)
	}
}

func renderRuntimeDocumentation(model Model) string {
	var buffer strings.Builder
	buffer.WriteString("# Embedded JavaScript runtime\n\n")
	buffer.WriteString("`muamba.yaml` is the acquisition and SHA-384 integrity source of truth. `assets/runtime.overlay.yaml` owns Goshtoso runtime order, loading defaults, and attribution metadata. Generated Go, site, and documentation files must not be edited by hand.\n\n")
	buffer.WriteString("Inspect the exact runtime linked into a Go binary with `assets.DefaultRuntimeManifest()`. Inspect normalized vendored hashes for cache busting with `assets.RuntimeHash(role)` or the complete acquisition registry with `assets.MuambaResources()`.\n\n")
	buffer.WriteString("Inspect generated identity and retained-license metadata with `assets.DefaultRuntimeMetadata()`. Runtime metadata does not replace `RuntimeAsset`: the latter remains the supported loading, override, SRI, enablement, and ordering contract.\n\n")
	buffer.WriteString("Pinned versions are the tested combination. Replacing URLs or versions configures loading; it does not guarantee compatibility with arbitrary combinations.\n\n")
	buffer.WriteString("| Order | Asset | Version | Role | Default | Minimal | Embedded URL | Primary URL | License |\n")
	buffer.WriteString("| ---: | --- | --- | --- | :---: | :---: | --- | --- | --- |\n")
	writeRuntimeDocumentationRow(&buffer, 0, model.Loader)
	for index, asset := range model.Dependencies {
		writeRuntimeDocumentationRow(&buffer, index+1, asset)
	}
	buffer.WriteString("\nRegenerate all consumers with `go run ./cmd/runtimegen`; verify acquisition integrity and generated drift with `go tool muamba verify --strict`, `go tool muamba generate-go --strict --check --dir assets --output muamba_gen.go`, and `go run ./cmd/runtimegen -check`.\n")
	return buffer.String()
}

func writeRuntimeDocumentationRow(buffer *strings.Builder, order int, asset Asset) {
	version := asset.Version
	if version == "" {
		version = "Goshtoso release"
	}
	primary := asset.URL
	if primary == "" {
		primary = asset.LocalURL
	}
	license := asset.License
	if license == "" {
		license = "Goshtoso"
	} else {
		license = fmt.Sprintf("[%s](../%s)", license, strings.TrimPrefix(asset.LicenseLocalURL, "/"))
	}
	fmt.Fprintf(buffer, "| %d | %s | `%s` | `%s` | %s | %s | `%s` | `%s` | %s |\n", order, escapeMarkdownCell(asset.Name), version, asset.Role, strconv.FormatBool(asset.Enabled), strconv.FormatBool(asset.IncludeInMinimal), asset.LocalURL, primary, license)
}

func allAssets(model Model) []Asset {
	assets := make([]Asset, 0, len(model.Dependencies)+1)
	assets = append(assets, model.Loader)
	return append(assets, model.Dependencies...)
}

func formatGo(source string) string {
	formatted, err := format.Source([]byte(source))
	if err != nil {
		panic(fmt.Sprintf("runtimegen: gofmt failed: %v\n%s", err, source))
	}
	return string(formatted)
}

func escapeMarkdownCell(value string) string {
	return strings.ReplaceAll(value, "|", "\\|")
}
