package conformanceledger

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
)

// GenerateSiteLedgerSource produces the narrow, site-module-local portion of
// the ledger needed by the e2e/full harness. The site is a separate Go module
// pinned to a published Goshtoso release, so importing this root internal
// tooling package would silently make its standalone proof depend on an
// unreleased module. Keep the generated mirror source-derived and byte-checked.
func GenerateSiteLedgerSource(repoRoot string) (map[string][]byte, error) {
	files := map[string]string{
		"schema.go":                   "internal/conformanceledger/schema.go",
		"bfull.go":                    "internal/conformanceledger/bfull.go",
		"inventory.go":                "internal/conformanceledger/inventory.go",
		"checklist.go":                "internal/conformanceledger/checklist.go",
		"themeinventory/inventory.go": "internal/themeinventory/inventory.go",
	}
	generated := make(map[string][]byte, len(files))
	for output, input := range files {
		source, err := os.ReadFile(filepath.Join(repoRoot, input))
		if err != nil {
			return nil, fmt.Errorf("read %s: %w", input, err)
		}
		if input == "internal/conformanceledger/inventory.go" {
			source = bytes.ReplaceAll(source,
				[]byte(`"github.com/araihu/goshtoso/internal/themeinventory"`),
				[]byte(`"github.com/araihu/goshtoso/site/internal/conformanceledger/themeinventory"`))
		}
		header := []byte("// Code generated by conformanceledger.GenerateSiteLedgerSource from " + input + "; DO NOT EDIT.\n")
		generated[output] = append(header, source...)
	}
	return generated, nil
}

// WriteSiteLedgerSource writes a generated mirror atomically by path. It is
// intentionally invoked only by the root tooling CLI; site e2e never imports
// unreleased root-module internals.
func WriteSiteLedgerSource(repoRoot, outputDir string) error {
	generated, err := GenerateSiteLedgerSource(repoRoot)
	if err != nil {
		return err
	}
	for output, source := range generated {
		path := filepath.Join(outputDir, output)
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			return fmt.Errorf("create site ledger directory: %w", err)
		}
		if err := os.WriteFile(path, source, 0o600); err != nil {
			return fmt.Errorf("write generated site ledger %s: %w", path, err)
		}
	}
	return nil
}
