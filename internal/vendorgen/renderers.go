package vendorgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"strconv"
	"strings"
)

func renderRuntimeManifest(manifest runtimeManifest) string {
	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by vendorgen. DO NOT EDIT.\n")
	buffer.WriteString("// Source of truth: assets/js/runtime/manifest.json\n\n")
	buffer.WriteString("package assets\n\n")
	buffer.WriteString("const (\n")
	assets := append([]runtimeAssetManifest{manifest.Loader}, manifest.Dependencies...)
	for _, asset := range assets {
		fmt.Fprintf(&buffer, "\t// RuntimeRole%s identifies %s.\n", asset.RoleGoName, asset.Name)
		fmt.Fprintf(&buffer, "\tRuntimeRole%s RuntimeAssetRole = %q\n", asset.RoleGoName, asset.Role)
	}
	buffer.WriteString(")\n\n")
	buffer.WriteString("func defaultRuntimeLoader() RuntimeAsset {\n\treturn ")
	writeRuntimeAsset(&buffer, manifest.Loader)
	buffer.WriteString("\n}\n\n")
	buffer.WriteString("func defaultRuntimeDependencies() []RuntimeAsset {\n\treturn []RuntimeAsset{\n")
	for _, asset := range manifest.Dependencies {
		buffer.WriteString("\t\t")
		writeRuntimeAsset(&buffer, asset)
		buffer.WriteString(",\n")
	}
	buffer.WriteString("\t}\n}\n")
	return formatGo(buffer.String())
}

func writeRuntimeAsset(buffer *bytes.Buffer, asset runtimeAssetManifest) {
	primary := asset.GoName + "URL"
	if asset.CDNURL != "" {
		primary = asset.GoName + "CDNURL"
	}
	fmt.Fprintf(buffer, "RuntimeAsset{Role: RuntimeRole%s, Kind: RuntimeAssetScript, Name: %q, Version: %q, Homepage: %q, License: %q, Purpose: %q, PrimaryURL: %s, LocalURL: %sURL", asset.RoleGoName, asset.Name, asset.Version, asset.Homepage, asset.License, asset.Purpose, primary, asset.GoName)
	if asset.Integrity != "" {
		fmt.Fprintf(buffer, ", Integrity: %sIntegrity", asset.GoName)
	}
	if asset.Enabled {
		buffer.WriteString(", Enabled: true")
	}
	if asset.IncludeInMinimal {
		buffer.WriteString(", IncludeInMinimal: true")
	}
	if asset.Defer {
		buffer.WriteString(", Defer: true")
	}
	if asset.WaitForWindowLoaded {
		buffer.WriteString(", WaitForWindowLoaded: true")
	}
	buffer.WriteString("}")
}

func renderVersionsCompatibility(manifest runtimeManifest) string {
	contents, err := json.MarshalIndent(vendoredDependencies(manifest), "", "  ")
	if err != nil {
		panic(fmt.Sprintf("vendorgen: render versions compatibility: %v", err))
	}
	return string(contents) + "\n"
}

func renderRuntimeAttributions(manifest runtimeManifest) string {
	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by vendorgen. DO NOT EDIT.\n")
	buffer.WriteString("// Source of truth: assets/js/runtime/manifest.json\n\n")
	buffer.WriteString("package legalpages\n\n")
	buffer.WriteString("var runtimeAttributions = []attribution{\n")
	for _, asset := range manifest.Dependencies {
		if !asset.Attribution {
			continue
		}
		fmt.Fprintf(&buffer, "\t{Name: %q, Href: %q, Version: %q, LocalURL: %q, License: %q, Note: %q},\n", asset.Name, asset.Homepage, asset.Version, asset.LocalURL, asset.License, asset.Purpose)
	}
	buffer.WriteString("}\n")
	return formatGo(buffer.String())
}

func renderRuntimeDocumentation(manifest runtimeManifest) string {
	var buffer strings.Builder
	buffer.WriteString("# Embedded JavaScript runtime\n\n")
	buffer.WriteString("`assets/js/runtime/manifest.json` is the checked-in source of truth for the embedded JavaScript inventory, execution order, pinned third-party versions, loading defaults, and attribution metadata. Generated Go and site files must not be edited by hand.\n\n")
	buffer.WriteString("Inspect the exact runtime linked into a Go binary with `assets.DefaultRuntimeManifest()`. The legacy `/assets/js/runtime/versions.json` endpoint remains a generated compatibility view for version-only tooling.\n\n")
	buffer.WriteString("Pinned versions are the tested combination. Replacing URLs or versions configures loading; it does not guarantee compatibility with arbitrary combinations.\n\n")
	buffer.WriteString("| Order | Asset | Version | Role | Default | Minimal | Embedded URL | Primary URL | License |\n")
	buffer.WriteString("| ---: | --- | --- | --- | :---: | :---: | --- | --- | --- |\n")
	writeRuntimeDocumentationRow(&buffer, 0, manifest.Loader)
	for index, asset := range manifest.Dependencies {
		writeRuntimeDocumentationRow(&buffer, index+1, asset)
	}
	buffer.WriteString("\nRegenerate all consumers with `go run ./cmd/vendorgen`; verify local hashes and generated drift with `go run ./cmd/vendorgen -check`; fetch every declared CDN URL and verify the same canonical hashes with `go run ./cmd/vendorgen -check -verify-remote`.\n")
	return buffer.String()
}

func writeRuntimeDocumentationRow(buffer *strings.Builder, order int, asset runtimeAssetManifest) {
	version := asset.Version
	if version == "" {
		version = "Goshtoso release"
	}
	primary := asset.CDNURL
	if primary == "" {
		primary = asset.LocalURL
	} else {
		primary = strings.ReplaceAll(primary, "{v}", asset.Version)
	}
	license := asset.License
	if license == "" {
		license = "Goshtoso"
	}
	fmt.Fprintf(buffer, "| %d | %s | `%s` | `%s` | %s | %s | `%s` | `%s` | %s |\n", order, escapeMarkdownCell(asset.Name), version, asset.Role, yesNo(asset.Enabled), yesNo(asset.IncludeInMinimal), asset.LocalURL, primary, license)
}

func renderVendorConstants(manifest runtimeManifest) string {
	var buffer bytes.Buffer
	buffer.WriteString("// Code generated by vendorgen. DO NOT EDIT.\n")
	buffer.WriteString("// Source of truth: assets/js/runtime/manifest.json and vendored bytes\n\n")
	buffer.WriteString("package assets\n\nconst (\n")
	assets := append([]runtimeAssetManifest{manifest.Loader}, manifest.Dependencies...)
	for _, asset := range assets {
		fmt.Fprintf(&buffer, "\t%sURL = %q\n", asset.GoName, asset.LocalURL)
		if asset.Version != "" {
			fmt.Fprintf(&buffer, "\truntimeVersion%s = %q\n", asset.GoName, asset.Version)
		}
		if asset.CDNURL != "" {
			fmt.Fprintf(&buffer, "\t%sCDNURL = %q\n", asset.GoName, strings.ReplaceAll(asset.CDNURL, "{v}", asset.Version))
			fmt.Fprintf(&buffer, "\t%sIntegrity = %q\n", asset.GoName, asset.Integrity)
		}
	}
	buffer.WriteString(")\n")
	return formatGo(buffer.String())
}

func formatGo(source string) string {
	formatted, err := format.Source([]byte(source))
	if err != nil {
		panic(fmt.Sprintf("vendorgen: gofmt failed: %v\n%s", err, source))
	}
	return string(formatted)
}

func yesNo(value bool) string {
	return strconv.FormatBool(value)
}

func escapeMarkdownCell(value string) string {
	return strings.ReplaceAll(value, "|", "\\|")
}
