package iconcatalog

import (
	"bytes"
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strings"
	"unicode"
)

// Options controls catalog selection and generated Go source.
type Options struct {
	CatalogPath string
	OutputPath  string
	Package     string
	Namespace   string
	Product     string
	SpriteURL   string
	ConstPrefix string
	Check       bool
}

type glyph struct {
	goName string
	Asset
}

// Generate returns formatted Go source for the namespace and product selected
// by opts. Only assets that declare a sprite symbol are eligible bindings.
func Generate(catalog Catalog, opts Options) ([]byte, error) {
	if err := validateOptions(opts); err != nil {
		return nil, err
	}

	selected := make([]glyph, 0, len(catalog.Assets))
	seenIdentifiers := make(map[string]string)
	seenSymbols := make(map[string]string)
	for _, asset := range catalog.Assets {
		if asset.Namespace != opts.Namespace || asset.Product != opts.Product {
			continue
		}
		if asset.SpriteSymbol == "" {
			continue
		}
		if err := validateAsset(asset); err != nil {
			return nil, err
		}
		if first, exists := seenSymbols[asset.SpriteSymbol]; exists {
			return nil, fmt.Errorf("duplicate spriteSymbol %q from %q and %q", asset.SpriteSymbol, first, asset.CanonicalName)
		}
		seenSymbols[asset.SpriteSymbol] = asset.CanonicalName
		goName, err := identifier(opts.ConstPrefix, opts.Namespace, asset.CanonicalName)
		if err != nil {
			return nil, err
		}
		if first, exists := seenIdentifiers[goName]; exists {
			return nil, fmt.Errorf("identifier collision %q from %q and %q", goName, first, asset.CanonicalName)
		}
		seenIdentifiers[goName] = asset.CanonicalName
		selected = append(selected, glyph{goName: goName, Asset: asset})
	}
	if len(selected) == 0 {
		return nil, fmt.Errorf("no sprite assets for namespace %q and product %q", opts.Namespace, opts.Product)
	}

	sort.Slice(selected, func(i, j int) bool {
		if selected[i].CanonicalName == selected[j].CanonicalName {
			return selected[i].SpriteSymbol < selected[j].SpriteSymbol
		}
		return selected[i].CanonicalName < selected[j].CanonicalName
	})

	var b bytes.Buffer
	b.WriteString("// Code generated by iconcatalog. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Source catalog SHA-256: %s\n", catalog.Hash)
	fmt.Fprintf(&b, "// Source catalog schema: v%d\n\n", catalog.SchemaVersion)
	fmt.Fprintf(&b, "package %s\n\n", opts.Package)
	b.WriteString("import \"github.com/araihu/goshtoso/components/icon\"\n\n")
	b.WriteString("type Glyph struct {\n")
	b.WriteString("\tGoName string\n")
	b.WriteString("\tCanonicalName string\n")
	b.WriteString("\tSymbol icon.Symbol\n")
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "const SpriteURL = %q\n\n", opts.SpriteURL)
	b.WriteString("const (\n")
	for _, entry := range selected {
		fmt.Fprintf(&b, "\t%s icon.Symbol = %q\n", entry.goName, entry.SpriteSymbol)
	}
	b.WriteString(")\n\n")
	b.WriteString("var Glyphs = []Glyph{\n")
	for _, entry := range selected {
		fmt.Fprintf(&b, "\t{\n\t\tGoName: %q,\n\t\tCanonicalName: %q,\n\t\tSymbol: %s,\n\t},\n", entry.goName, entry.CanonicalName, entry.goName)
	}
	b.WriteString("}\n")

	generated, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated source: %w", err)
	}
	return generated, nil
}

func validateOptions(opts Options) error {
	for _, field := range []struct {
		name, value string
	}{
		{"package", opts.Package},
		{"namespace", opts.Namespace},
		{"product", opts.Product},
		{"sprite-url", opts.SpriteURL},
		{"const-prefix", opts.ConstPrefix},
	} {
		if field.value == "" {
			return fmt.Errorf("%s is required", field.name)
		}
	}
	if opts.Package == "_" {
		return fmt.Errorf("package %q is not a valid Go package name", opts.Package)
	}
	if !isIdentifier(opts.Package) {
		if token.Lookup(opts.Package).IsKeyword() {
			return fmt.Errorf("package %q is a Go keyword", opts.Package)
		}
		return fmt.Errorf("package %q is not a Go identifier", opts.Package)
	}
	if !isIdentifier(opts.ConstPrefix) {
		if token.Lookup(opts.ConstPrefix).IsKeyword() {
			return fmt.Errorf("const-prefix %q is a Go keyword", opts.ConstPrefix)
		}
		return fmt.Errorf("const-prefix %q is not a Go identifier", opts.ConstPrefix)
	}
	return nil
}

func validateAsset(asset Asset) error {
	if asset.CanonicalName == "" {
		return fmt.Errorf("empty canonicalName")
	}
	if asset.Format != "svg" {
		return fmt.Errorf("asset %q has unsupported format %q", asset.CanonicalName, asset.Format)
	}
	if asset.ColorBehavior != "monochrome" && asset.ColorBehavior != "tintable" && asset.ColorBehavior != "protected" {
		return fmt.Errorf("asset %q has incompatible colorBehavior %q", asset.CanonicalName, asset.ColorBehavior)
	}
	return nil
}

func identifier(prefix, namespace, canonicalName string) (string, error) {
	name := strings.TrimPrefix(canonicalName, namespace+"-")
	// schema-v1 Heroicons canonical names carry their sprite-family "hi" marker.
	// The generated package already scopes those constants to that family, so the
	// public constant names retain the documented Icon16Solid... form.
	name = strings.TrimPrefix(name, "hi-")
	var b strings.Builder
	b.WriteString(prefix)
	wordStart := true
	for _, r := range name {
		if r == '-' {
			wordStart = true
			continue
		}
		if (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') && (r < '0' || r > '9') {
			return "", fmt.Errorf("canonicalName %q cannot form a Go identifier", canonicalName)
		}
		if wordStart {
			b.WriteRune(unicode.ToUpper(r))
			wordStart = false
			continue
		}
		b.WriteRune(r)
	}
	if b.Len() == len(prefix) || !isIdentifier(b.String()) {
		return "", fmt.Errorf("canonicalName %q cannot form a Go identifier", canonicalName)
	}
	return b.String(), nil
}

func isIdentifier(value string) bool {
	if token.Lookup(value).IsKeyword() {
		return false
	}
	for i, r := range value {
		if r == '_' || 'a' <= r && r <= 'z' || 'A' <= r && r <= 'Z' || i > 0 && '0' <= r && r <= '9' {
			continue
		}
		return false
	}
	return value != ""
}
