package sidebar

import (
	"maps"
	"strings"

	"github.com/a-h/templ"
)

// Item represents a single navigation item in the sidebar
type Item struct {
	// ID is the unique identifier for the item
	ID string
	// Label is the display text
	Label string
	// Icon is an optional icon (templ.Component)
	Icon templ.Component
	// Href is the link URL
	Href string
	// Active indicates if this item is currently active
	Active bool
	// Disabled prevents interaction
	Disabled bool
	// Badge is an optional badge text (e.g., "New", "Soon")
	Badge string
	// BadgeClass overrides the default badge styling.
	BadgeClass string
	// Items contains child items for nested navigation
	Items []Item
	// Collapsible renders child items behind a disclosure control.
	Collapsible bool
	// Open controls the initial disclosure state for collapsible child items.
	Open bool
	// Title overrides the generated browser tooltip text for sidebar links.
	// When empty, sidebar links default to Item.Label unless DisableAutoTitle is true
	// or LinkAttrs already contains a title.
	Title string
	// DisableAutoTitle prevents the sidebar from adding a title attribute from Label.
	DisableAutoTitle bool
	// AriaLabel optionally overrides the accessible name on sidebar links.
	// This is not generated by default because aria-label replaces the link's
	// descendant text, including badges and active state markers.
	AriaLabel string
	// LinkAttrs are extra HTML attributes spread onto the <a> element.
	// Use for HTMX, Alpine.js, or other consumer-specific attributes.
	LinkAttrs templ.Attributes
}

// Config holds configuration for the sidebar
type Config struct {
	// Items are the top-level navigation items (icon links above sections)
	Items []Item
	// SectionsTitle is an optional header rendered above the sections (e.g. "Components")
	SectionsTitle string
	// Sections are grouped navigation sections with titles and left-border items
	Sections []Section
	// Logo is the logo component (optional)
	Logo templ.Component
	// LogoText is the text-only logo if no component provided
	LogoText string
	// LogoHref is the link for the logo (default: "/")
	LogoHref string
	// ShowSearch enables the search input
	ShowSearch bool
	// SearchPlaceholder is the placeholder text for search
	SearchPlaceholder string
	// RootClass allows additional CSS classes on the sidebar root.
	RootClass string
	// SearchSlot replaces the default search input with a custom component.
	// When set, ShowSearch is ignored.
	SearchSlot templ.Component
	// FooterSlot renders content at the bottom of the sidebar (e.g., profile menu).
	FooterSlot templ.Component
	// DisableSkipLink omits Sidebar's internal skip link when a containing
	// application frame, such as AppShell, already owns page-level skip navigation.
	DisableSkipLink bool
}

// OverlayConfig wraps a Sidebar in an Alpine-controlled off-canvas panel.
type OverlayConfig struct {
	// ID identifies the overlay panel.
	ID string
	// Sidebar is the sidebar configuration rendered inside the overlay panel.
	Sidebar Config
	// Trigger replaces the default menu icon inside the trigger button.
	Trigger templ.Component
	// TriggerLabel is the accessible label for the trigger button.
	// Default: "Open sidebar".
	TriggerLabel string
	// RootClass allows additional CSS classes on the overlay root.
	RootClass string
	// TriggerClass allows additional CSS classes on the trigger button.
	TriggerClass string
	// BackdropPositionClass controls backdrop positioning.
	// Default: "fixed inset-0".
	BackdropPositionClass string
	// BackdropClass allows additional CSS classes on the backdrop.
	BackdropClass string
	// PanelPositionClass controls panel positioning.
	// Default: "fixed inset-y-0 left-0".
	PanelPositionClass string
	// PanelWidthClass controls the panel width.
	// Default: "w-72".
	PanelWidthClass string
	// PanelClass allows additional CSS classes on the off-canvas panel wrapper.
	PanelClass string
}

// Section represents a group of navigation items
type Section struct {
	// Title is the section header
	Title string
	// Items are the navigation items in this section
	Items []Item
	// Collapsible renders direct child groups behind independent disclosure controls.
	// Each group starts closed unless the parent Item sets Open.
	Collapsible bool
	// IndentItems offsets the section item group from the title.
	IndentItems bool
}

// ContainerClasses returns the container CSS classes
func (cfg Config) containerClasses() string {
	return "h-full w-full border-r border-outline bg-surface dark:border-outline-dark dark:bg-surface-dark flex flex-col"
}

// NavClasses returns the navigation container classes
func (cfg Config) navClasses() string {
	return "flex-1 overflow-y-auto sidebar-scroll scrollbar-custom p-4"
}

// PanelID returns the id for the overlay panel.
func (cfg OverlayConfig) panelID() string {
	if id := strings.TrimSpace(cfg.ID); id != "" {
		return id + "-panel"
	}
	return "sidebar-overlay-panel"
}

// TriggerLabelText returns the trigger button accessible label.
func (cfg OverlayConfig) triggerLabelText() string {
	if label := strings.TrimSpace(cfg.TriggerLabel); label != "" {
		return label
	}
	return "Open sidebar"
}

// RootClasses returns classes for the overlay root.
func (cfg OverlayConfig) rootClasses() string {
	return strings.TrimSpace(cfg.RootClass)
}

// TriggerClasses returns classes for the overlay trigger button.
func (cfg OverlayConfig) triggerClasses() string {
	base := "inline-flex min-h-11 min-w-11 items-center justify-center rounded-radius p-2 text-on-surface transition-colors hover:bg-surface-alt focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-primary dark:text-on-surface-dark dark:hover:bg-surface-dark-alt dark:focus-visible:outline-primary-dark"
	if cfg.TriggerClass != "" {
		base += " " + cfg.TriggerClass
	}
	return base
}

// BackdropClasses returns classes for the overlay backdrop.
func (cfg OverlayConfig) backdropClasses() string {
	position := strings.TrimSpace(cfg.BackdropPositionClass)
	if position == "" {
		position = "fixed inset-0"
	}
	base := position + " z-30 bg-backdrop/50"
	if cfg.BackdropClass != "" {
		base += " " + cfg.BackdropClass
	}
	return base
}

// PanelClasses returns classes for the off-canvas panel wrapper.
func (cfg OverlayConfig) panelClasses() string {
	position := strings.TrimSpace(cfg.PanelPositionClass)
	if position == "" {
		position = "fixed inset-y-0 left-0"
	}
	width := strings.TrimSpace(cfg.PanelWidthClass)
	if width == "" {
		width = "w-72"
	}
	base := position + " z-40 " + width
	if cfg.PanelClass != "" {
		base += " " + cfg.PanelClass
	}
	return base
}

func sidebarLinkAttrs(item Item) templ.Attributes {
	attrs := templ.Attributes{}
	maps.Copy(attrs, item.LinkAttrs)

	if _, ok := attrs["title"]; !ok {
		title := strings.TrimSpace(item.Title)
		if title == "" && !item.DisableAutoTitle {
			title = strings.TrimSpace(item.Label)
		}
		if title != "" {
			attrs["title"] = title
		}
	}

	if _, ok := attrs["aria-label"]; !ok {
		if label := strings.TrimSpace(item.AriaLabel); label != "" {
			attrs["aria-label"] = label
		}
	}

	if len(attrs) == 0 {
		return nil
	}
	return attrs
}

func sidebarBadgeClasses(item Item, section bool) string {
	base := "ml-auto shrink-0 static inline-flex items-center justify-center rounded-radius px-1.5 py-0.5 text-[10px] font-bold leading-none"
	if section {
		base += " h-4"
	} else {
		base += " min-h-5"
	}
	if item.BadgeClass != "" {
		return base + " " + item.BadgeClass
	}
	return base + " bg-primary text-on-primary dark:bg-primary-dark dark:text-on-primary-dark"
}

func sidebarDisclosureData(open bool) string {
	if open {
		return "{ open: true }"
	}
	return "{ open: false }"
}

func sidebarChildrenAttrs(open bool) templ.Attributes {
	if open {
		return nil
	}
	return templ.Attributes{"style": "display: none;"}
}

func sidebarChildrenID(item Item) string {
	if item.ID != "" {
		return item.ID + "-children"
	}
	return "sidebar-children"
}

func sidebarSectionItemsClasses(section Section) string {
	if section.IndentItems {
		return "ml-4 flex flex-col"
	}
	return "flex flex-col"
}
