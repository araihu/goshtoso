package siteassets

import (
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"
)

func TestHandlerServesGeneratedBundleButNotAuthoredSources(t *testing.T) {
	t.Parallel()

	recorder := httptest.NewRecorder()
	Handler().ServeHTTP(recorder, httptest.NewRequest(http.MethodGet, DemoBundleURL, nil))
	if recorder.Code != http.StatusOK {
		t.Fatalf("GET %s status = %d, want %d", DemoBundleURL, recorder.Code, http.StatusOK)
	}
	if !strings.HasPrefix(recorder.Body.String(), "// Code generated by go run ./cmd/jsbuild; DO NOT EDIT.") {
		t.Fatalf("GET %s did not return generated bundle", DemoBundleURL)
	}

	recorder = httptest.NewRecorder()
	Handler().ServeHTTP(recorder, httptest.NewRequest(http.MethodGet, "/site-assets/js/src/chat.js", nil))
	if recorder.Code != http.StatusNotFound {
		t.Fatalf("authored source status = %d, want %d", recorder.Code, http.StatusNotFound)
	}
}
